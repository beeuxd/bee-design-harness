#!/usr/bin/env node

/**
 * PreToolUse hook: Build Gate Guard
 * Schema-level enforcement of the pipeline's build gate (OpenDev pattern: gates
 * enforced at the tool layer, not by instructions). Writing UI source files
 * before the hifi-gate has recorded evidence triggers a user-confirmation
 * dialog — the director can override, but never silently.
 * Silent outside harness projects and once the gate has passed.
 */

const fs = require("fs");

const input = JSON.parse(fs.readFileSync("/dev/stdin", "utf8"));
const filePath = input.tool_input?.file_path;
if (!filePath) process.exit(0);

// Only harness projects (cwd is the project root when hooks run).
if (!fs.existsSync("DESIGN.md")) process.exit(0);

// Only UI source files inside build directories.
const isUiSource =
  /(^|\/)(app|src|components|pages)\/.*\.(tsx|jsx|vue|svelte|css)$/.test(filePath) &&
  !/tokens\.css$/.test(filePath); // tokens.css is generated by pnpm tokens, guarded elsewhere

if (!isUiSource) process.exit(0);

// Gate check: a dated row under "## Gate Ledger" in wireframes.md = hifi-gate evidence exists.
let gatePassed = false;
try {
  const wf = fs.readFileSync("docs/ideation/wireframes.md", "utf8");
  const ledger = wf.split(/^##\s*Gate Ledger.*$/im)[1] || "";
  gatePassed = /\b\d{4}-\d{2}-\d{2}\b/.test(ledger);
} catch { /* no wireframes.md → gate not passed */ }

if (!gatePassed) {
  process.stdout.write(
    JSON.stringify({
      hookSpecificOutput: {
        hookEventName: "PreToolUse",
        permissionDecision: "ask",
        permissionDecisionReason:
          `Build gate: ${filePath} is UI source, but docs/ideation/wireframes.md has no Gate Ledger evidence yet — the pipeline hasn't passed /hifi-gate. Building before the gate is how unreviewed visuals ship. Override deliberately?`,
      },
    })
  );
}
process.exit(0);
